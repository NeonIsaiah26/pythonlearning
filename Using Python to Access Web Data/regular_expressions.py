# regular expressions
# ^ matches the beginning 
# $ matches the end of line 
# , matches any character 
# \s, \S matches whitespace and none whitespace characters
# * repeats a character zero or more times
# *? repeats a character zero or more times  (none-greedy)
# + runs a character one or more times
# +? runs a character one or more times (none-greedy)
# [aeiou] listed set 
# [^XYZ] macthes a character not in the listed set 
# [a-z0-9] The set of characters that can include a range 
